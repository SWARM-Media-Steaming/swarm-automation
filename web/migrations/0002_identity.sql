-- Identity model of the hosted backend (issue #438, part of #413).
--
-- Gives sign-in a relational shape that more OIDC providers can join later:
-- a `users` row is a person, `user_identities` holds how they sign in (GitHub
-- is the only provider today: no username, email or password login), and
-- tenant ownership and membership are real foreign keys. Builds on 0001:
-- `web_users` / `web_sessions` become `users` / `sessions` (the rename keeps
-- their rows and every foreign key that points at them), and `github_id` and
-- `login` move out of `users` into `user_identities` after a backfill.
--
-- Idempotent and re-runnable: every statement is guarded (IF NOT EXISTS, or a
-- DO block that checks the catalog first), so applying it twice, or on a
-- database that already has the final shape, changes nothing. The per-tenant
-- worker schema (`t_<tenant>`, SCHEMA_VERSION) is not touched.

DO $$
DECLARE
    leftover BIGINT;
BEGIN
    IF to_regclass('web_users') IS NOT NULL AND to_regclass('users') IS NULL THEN
        ALTER TABLE web_users RENAME TO users;
    END IF;
    IF to_regclass('web_sessions') IS NOT NULL AND to_regclass('sessions') IS NULL THEN
        ALTER TABLE web_sessions RENAME TO sessions;
    END IF;
    -- Re-applying 0001 after this has run (psql -f over every file) recreates
    -- its two tables empty under the old names; drop those leftovers, but never
    -- one that holds rows.
    IF to_regclass('web_sessions') IS NOT NULL AND to_regclass('sessions') IS NOT NULL THEN
        EXECUTE 'SELECT count(*) FROM web_sessions' INTO leftover;
        IF leftover = 0 THEN
            DROP TABLE web_sessions;
        END IF;
    END IF;
    IF to_regclass('web_users') IS NOT NULL AND to_regclass('users') IS NOT NULL
       AND to_regclass('web_sessions') IS NULL THEN
        EXECUTE 'SELECT count(*) FROM web_users' INTO leftover;
        IF leftover = 0 THEN
            DROP TABLE web_users;
        END IF;
    END IF;
END
$$;

